const ImageLoader = ({
  imageKey,
  hoverImage,
  isHovered = false,
  className,
  onClick,
  style,
  onLoad,
}) => {
  // Check if the imageKey exists in our predefined images
  const getPredefinedImage = (key) => {
    if (key && key in images) {
      return images[key];
    }
    return null;
  };

  // Determine which image to show
  const imageSrc =
    isHovered && hoverImage
      ? (getPredefinedImage(hoverImage) ?? hoverImage)
      : (getPredefinedImage(imageKey) ?? imageKey);

  // Fallback if image is not found
  const fallbackSrc = Gallery;

  return (
    <img
      src={imageSrc ? imageSrc : fallbackSrc}
      alt={imageKey}
      className={className}
      onError={(e) => {
        e.target.src = fallbackSrc;
      }}
      onClick={onClick ? onClick : undefined}
      style={style}
      onLoad={onLoad}
    />
  );
};

export default ImageLoader;
